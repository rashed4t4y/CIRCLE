CREATE TABLE conversations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_low INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_high INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (user_low < user_high),
  UNIQUE (user_low, user_high)
);
CREATE INDEX conversations_low_activity_idx ON conversations(user_low, updated_at DESC, id DESC);
CREATE INDEX conversations_high_activity_idx ON conversations(user_high, updated_at DESC, id DESC);
CREATE TABLE messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content VARCHAR(4000) NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 4000),
  client_id UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  read_at TIMESTAMPTZ,
  CHECK (sender_id <> recipient_id),
  UNIQUE (conversation_id, sender_id, client_id)
);
CREATE INDEX messages_history_idx ON messages(conversation_id, id DESC);
CREATE INDEX messages_unread_idx ON messages(recipient_id, conversation_id, id) WHERE read_at IS NULL;
CREATE INDEX messages_sender_idx ON messages(sender_id);
CREATE INDEX messages_recipient_idx ON messages(recipient_id);
