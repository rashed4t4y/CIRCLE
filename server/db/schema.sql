-- CIRCLE migration 001: normalized PostgreSQL schema.
-- Applied transactionally by migrate.js; this file never drops user data.
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(80) NOT NULL CHECK (char_length(btrim(full_name)) BETWEEN 1 AND 80),
  username VARCHAR(24) NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9_]{3,24}$'),
  email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash TEXT NOT NULL,
  seed_key TEXT UNIQUE,
  bio VARCHAR(240) NOT NULL DEFAULT '',
  avatar_url VARCHAR(2048),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS posts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content VARCHAR(500) NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 500),
  image_url VARCHAR(2048),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  seed_key TEXT UNIQUE
);
CREATE TABLE IF NOT EXISTS comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content VARCHAR(1000) NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  seed_key TEXT UNIQUE
);
CREATE TABLE IF NOT EXISTS likes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (post_id, user_id)
);
CREATE TABLE IF NOT EXISTS follows (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  follower_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  following_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (follower_id, following_id),
  CHECK (follower_id <> following_id)
);
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  actor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type VARCHAR(16) NOT NULL CHECK (type IN ('like', 'comment', 'follow')),
  post_id INTEGER REFERENCES posts(id) ON DELETE CASCADE,
  comment_id INTEGER REFERENCES comments(id) ON DELETE CASCADE,
  is_read BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  seed_key TEXT UNIQUE,
  CHECK (recipient_id <> actor_id),
  CHECK (
    (type = 'follow' AND post_id IS NULL AND comment_id IS NULL) OR
    (type = 'like' AND post_id IS NOT NULL AND comment_id IS NULL) OR
    (type = 'comment' AND post_id IS NOT NULL AND comment_id IS NOT NULL)
  )
);
-- Store SHA-256 hashes of random cookie tokens, never raw tokens.
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at > created_at)
);
CREATE INDEX IF NOT EXISTS posts_feed_idx ON posts (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS posts_user_feed_idx ON posts (user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS comments_post_idx ON comments (post_id, created_at, id);
CREATE INDEX IF NOT EXISTS comments_user_idx ON comments (user_id);
CREATE INDEX IF NOT EXISTS likes_user_idx ON likes (user_id);
CREATE INDEX IF NOT EXISTS follows_following_idx ON follows (following_id, follower_id);
CREATE INDEX IF NOT EXISTS notifications_recipient_idx ON notifications (recipient_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS notifications_unread_idx ON notifications (recipient_id) WHERE is_read = false;
CREATE INDEX IF NOT EXISTS notifications_actor_idx ON notifications (actor_id);
CREATE INDEX IF NOT EXISTS notifications_post_idx ON notifications (post_id);
CREATE INDEX IF NOT EXISTS notifications_comment_idx ON notifications (comment_id);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions (user_id);
CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON sessions (expires_at);
CREATE INDEX IF NOT EXISTS users_name_idx ON users (lower(full_name));

